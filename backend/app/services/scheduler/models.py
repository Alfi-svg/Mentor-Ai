"""Domain data models and value objects for the deterministic scheduler."""

import uuid
from datetime import UTC, date, datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


class TimeInterval(BaseModel):
    """Immutable interval representation [start_time, end_time]."""

    start_time: datetime
    end_time: datetime

    @field_validator("start_time", "end_time", mode="after")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v.astimezone(UTC)

    @property
    def duration_minutes(self) -> int:
        return int((self.end_time - self.start_time).total_seconds() / 60)

    def overlaps(self, other: "TimeInterval") -> bool:
        """Return True if intervals overlap by any non-zero duration."""
        return max(self.start_time, other.start_time) < min(self.end_time, other.end_time)

    def contains(self, timestamp: datetime) -> bool:
        """Return True if timestamp is inside [start_time, end_time)."""
        ts_utc = timestamp if timestamp.tzinfo is not None else timestamp.replace(tzinfo=UTC)
        ts_utc = ts_utc.astimezone(UTC)
        return self.start_time <= ts_utc < self.end_time

    model_config = ConfigDict(frozen=True)


class SchedulableTask(BaseModel):
    """Input task specification for the scheduler."""

    id: uuid.UUID
    title: str
    duration_minutes: int = Field(ge=1, le=720)
    priority: Literal["P1", "P2", "P3", "P4"] = "P3"
    deadline: datetime | None = None
    energy_level: Literal["high", "medium", "low"] = "medium"
    constraints: dict[str, Any] = Field(default_factory=dict)
    allow_split: bool = False

    @field_validator("deadline", mode="after")
    @classmethod
    def ensure_utc_deadline(cls, v: datetime | None) -> datetime | None:
        if v is None:
            return None
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v.astimezone(UTC)


class FixedEvent(BaseModel):
    """Fixed commitment that cannot be moved or split (class, meeting)."""

    id: uuid.UUID | None = None
    title: str
    start_time: datetime
    end_time: datetime
    is_all_day: bool = False
    location: str | None = None

    @field_validator("start_time", "end_time", mode="after")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v.astimezone(UTC)

    @property
    def interval(self) -> TimeInterval:
        return TimeInterval(start_time=self.start_time, end_time=self.end_time)


class ScheduleBlockProposal(BaseModel):
    """A discrete block allocated in a proposed schedule."""

    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    task_id: uuid.UUID | None = None
    calendar_event_id: uuid.UUID | None = None
    title: str
    start_time: datetime
    end_time: datetime
    block_type: Literal["task", "fixed_event", "break", "buffer"]
    is_fixed: bool = False

    @field_validator("start_time", "end_time", mode="after")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v.astimezone(UTC)

    @property
    def duration_minutes(self) -> int:
        return int((self.end_time - self.start_time).total_seconds() / 60)

    @property
    def interval(self) -> TimeInterval:
        return TimeInterval(start_time=self.start_time, end_time=self.end_time)


class UnscheduledTaskInfo(BaseModel):
    """Detailed diagnostic explanation of why a task could not be scheduled."""

    task_id: uuid.UUID
    task_title: str
    required_minutes: int
    priority: str
    deadline: datetime | None = None
    reason: str
    max_available_gap_minutes: int
    suggested_actions: list[str] = Field(default_factory=list)


class ScheduleValidationResult(BaseModel):
    """Verification results validating schedule soundness."""

    is_valid: bool
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


class ScheduleProposal(BaseModel):
    """Output generated by the deterministic scheduler."""

    schedule_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    target_date: date
    timezone: str
    status: Literal["feasible", "conflict_detected"]
    total_scheduled_minutes: int
    total_free_minutes: int
    blocks: list[ScheduleBlockProposal] = Field(default_factory=list)
    conflicts: list[str] = Field(default_factory=list)
    unscheduled_tasks: list[UnscheduledTaskInfo] = Field(default_factory=list)
    validation: ScheduleValidationResult
